#!/usr/bin/env bash
# Babdoduk resident operations on Linux: the Portal worker and the Dooray Radar of THIS checkout
# as systemd --user services, plus the operator commands of scripts/windows/*.cmd / *.ps1.
#
#   install        write both units (start with the graphical login) and the Python path;
#                  set the unified Ops Chrome mode if none is recorded. Starts nothing.
#   start | stop | status | recover          the Portal worker (watchdog)
#   radar-start | radar-stop | radar-status  the Dooray Radar
#   browser-start | browser-status | browser-recover   the Babdoduk Ops Chrome
#   remove         stop both workers and remove both units (state, profile and logs are kept)
#   run <args>     ggongbab_workers.py <args>, e.g. `run radar-once --dry-run`
#   alert <args>   scripts/alert_push.py <args>: Telegram push to the phone, e.g. `alert --status`
#
# Same model as the Windows tasks: the operator's own session, no stored password, no sudo, no
# wake timer. Workers stop through their control files; systemd stops only the supervisor
# (KillMode=process), so a stop never kills the Ops Chrome or its login.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
RUNNER="$ROOT/scripts/windows/ggongbab_workers.py"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
PORTAL_UNIT="babdoduk-portal-worker.service"
RADAR_UNIT="babdoduk-dooray-radar.service"
RADAR_STOP_WAIT=90   # seconds radar-stop waits for the Radar process to exit
PYTHON_FILE="$ROOT/.local/ops-python.txt"
RADAR_START_DELAY=120

fail() { echo "$1: verify the operations checkout and its services. Diagnostic values suppressed." >&2; exit 1; }

python_path() {
    if [[ -f "$PYTHON_FILE" ]]; then
        tr -d '\r\n' < "$PYTHON_FILE"
    elif [[ -x "$ROOT/.venv/bin/python" ]]; then
        echo "$ROOT/.venv/bin/python"
    else
        echo python3
    fi
}

runner() { "$(python_path)" "$RUNNER" "$@"; }

unit_text() {   # unit_text <worker action> <description> <python> [start delay seconds]
    local pre=""
    if [[ -n "${4:-}" ]]; then pre=$'ExecStartPre=/bin/sleep '"$4"$'\n'; fi
    cat <<EOF
# Generated by scripts/linux/ops.sh for this checkout. Reinstall instead of editing.
[Unit]
Description=Babdoduk $2 ($ROOT)
After=graphical-session.target
PartOf=graphical-session.target
StartLimitIntervalSec=600
StartLimitBurst=4

[Service]
Type=simple
TimeoutStartSec=300
WorkingDirectory=$ROOT
${pre}ExecStart=$3 $RUNNER $1
Restart=on-failure
RestartSec=60
KillMode=process
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=graphical-session.target
EOF
}

expected_unit() {   # expected_unit <unit file name>
    local py
    py="$(python_path)"
    case "$1" in
        "$PORTAL_UNIT") unit_text watch "Portal worker" "$py" ;;
        # The Radar never opens Chrome: it starts after the Portal worker has opened the Ops Chrome
        # at login (about a minute), as the Windows tasks' 30 s / 60 s logon delays did.
        "$RADAR_UNIT") unit_text radar "Dooray Radar" "$py" "$RADAR_START_DELAY" ;;
    esac
}

verify_unit() {   # the unit must be exactly the one this checkout generates
    [[ -f "$UNIT_DIR/$1" ]] || fail "TASK_NOT_INSTALLED"
    [[ "$(cat "$UNIT_DIR/$1")" == "$(expected_unit "$1")" ]] || fail "TASK_OWNER_UNVERIFIED"
}

install() {
    [[ "$ROOT" =~ [[:space:]%\\] ]] && fail "CHECKOUT_PATH_UNSUPPORTED"
    local py
    py="$(python_path)"
    py="$("$py" -c 'import sys; print(sys.executable)')" || fail "PYTHON_REQUIRED"
    [[ -x "$py" && ! "$py" =~ [[:space:]%\\] ]] || fail "PYTHON_REQUIRED"
    "$py" "$RUNNER" check || fail "CONFIGURATION_REQUIRED"
    for unit in "$PORTAL_UNIT" "$RADAR_UNIT"; do
        [[ -e "$UNIT_DIR/$unit" ]] && fail "TASK_ALREADY_EXISTS_REMOVE_FIRST"
    done
    mkdir -p "$ROOT/.local" "$UNIT_DIR"
    chmod 700 "$ROOT/.local"
    printf '%s\n' "$py" > "$PYTHON_FILE"
    if [[ ! -f "$ROOT/.local/ops-browser.json" ]]; then
        "$py" "$RUNNER" ops-browser-mode --to unified || fail "CONTROL_WRITE_FAILED"
    fi
    expected_unit "$PORTAL_UNIT" > "$UNIT_DIR/$PORTAL_UNIT"
    expected_unit "$RADAR_UNIT" > "$UNIT_DIR/$RADAR_UNIT"
    systemctl --user daemon-reload
    systemctl --user enable "$PORTAL_UNIT" "$RADAR_UNIT" >/dev/null
    # Both control files stay disabled: nothing scans until the operator runs start / radar-start.
    "$py" "$RUNNER" stop >/dev/null || fail "CONTROL_WRITE_FAILED"
    "$py" "$RUNNER" radar-disable || fail "CONTROL_WRITE_FAILED"
    echo "Installed. Nothing runs yet: open the Ops Chrome (browser-start), log in by hand, then start and radar-start."
}

action="${1:-}"
shift || true
case "$action" in
    install) install ;;
    start)
        verify_unit "$PORTAL_UNIT"
        runner check || fail "CONFIGURATION_REQUIRED"
        runner enable || fail "CONTROL_WRITE_FAILED"
        systemctl --user reset-failed "$PORTAL_UNIT" 2>/dev/null || true
        systemctl --user start "$PORTAL_UNIT"
        echo "Worker start requested. Use ops.sh status to inspect it." ;;
    stop) runner stop ;;
    status)
        runner status || true
        echo "Services      : portal $(systemctl --user is-active "$PORTAL_UNIT" 2>/dev/null || true)," \
             "radar $(systemctl --user is-active "$RADAR_UNIT" 2>/dev/null || true)" ;;
    recover) runner recover ;;
    radar-start)
        verify_unit "$RADAR_UNIT"
        runner check || fail "CONFIGURATION_REQUIRED"
        runner radar-enable || fail "CONTROL_WRITE_FAILED"
        systemctl --user reset-failed "$RADAR_UNIT" 2>/dev/null || true
        systemctl --user start --no-block "$RADAR_UNIT"
        echo "Radar start requested; its first scan follows in about $RADAR_START_DELAY s. Use ops.sh radar-status." ;;
    radar-stop)
        # Wait for the process to leave: a radar-start right after a stop that has not finished
        # finds the old process still active, starts nothing, and the Radar stays off (2026-10-29).
        runner radar-disable
        for _ in $(seq 1 "$RADAR_STOP_WAIT"); do
            systemctl --user is-active --quiet "$RADAR_UNIT" 2>/dev/null || { echo "Radar stopped."; exit 0; }
            sleep 1
        done
        echo "Radar disabled but still finishing a scan; run radar-start only after radar-status shows it stopped." ;;
    radar-status) runner status || true; runner alerts || true ;;
    browser-start) runner ops-browser-start ;;
    browser-status) runner ops-browser-status ;;
    browser-recover) runner ops-browser-recover ;;
    remove)
        verify_unit "$PORTAL_UNIT"
        verify_unit "$RADAR_UNIT"
        runner radar-disable
        runner stop || fail "WORKER_NOT_STOPPED"
        sleep 8
        systemctl --user disable --now "$PORTAL_UNIT" "$RADAR_UNIT" >/dev/null
        rm -f "$UNIT_DIR/$PORTAL_UNIT" "$UNIT_DIR/$RADAR_UNIT"
        systemctl --user daemon-reload
        echo "Services removed. Ops Chrome, profile, state and logs retained." ;;
    run) runner "$@" ;;
    alert) "$(python_path)" "$ROOT/scripts/alert_push.py" "$@" ;;
    *)
        sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
        exit 2 ;;
esac
